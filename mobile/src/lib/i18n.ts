export type Lang = "en" | "es";
export const deviceLang = (): Lang => (getLocales()[0]?.languageCode === "es" ? "es" : "en");
export const strings = (lang: Lang): Strings => (lang === "es" ? es : en);

export function formatDate(iso: string | null, lang: Lang, fallback: string): string {
  if (!iso) return fallback;
  return new Date(iso).toLocaleString(lang === "es" ? "es-US" : "en-US", { month: "short", day: "numeric", year: "numeric", hour: "numeric", minute: "2-digit" });
}

export function trialDaysLeft(trialEndsAt: string | null): number {
  if (!trialEndsAt) return 0;
  return Math.max(0, Math.ceil((new Date(trialEndsAt).getTime() - Date.now()) / 86_400_000));
}

/** A calendar day ("YYYY-MM-DD") as "Feb 26, 2024" / "26 feb 2024", the same in every time zone. */
export function formatDay(day: string | null, lang: Lang, fallback = "—"): string {
  if (!day) return fallback;
  const d = new Date(`${day.slice(0, 10)}T00:00:00Z`);
  if (Number.isNaN(d.getTime())) return fallback;
  return d.toLocaleDateString(lang === "es" ? "es-US" : "en-US", { month: "short", day: "numeric", year: "numeric", timeZone: "UTC" });
}

/** "Nov 6" / "6 nov" (adds the year when it isn't this year). */
export function shortDate(iso: string, lang: Lang): string {
  const d = new Date(iso);
  const sameYear = d.getFullYear() === new Date().getFullYear();
  return d.toLocaleDateString(lang === "es" ? "es-US" : "en-US", { month: "short", day: "numeric", ...(sameYear ? {} : { year: "numeric" }) });
}

/** "just now", "5 min ago", "2 h ago", "yesterday", "3 days ago", then a date. */
export function timeAgo(iso: string, lang: Lang, now: number = Date.now()): string {
  const t = strings(lang);
  const minutes = Math.max(0, Math.round((now - new Date(iso).getTime()) / 60_000));
  if (minutes < 1) return t.justNow;
  if (minutes < 60) return t.minutesAgo(minutes);
  const hours = Math.round(minutes / 60);
  if (hours < 24) return t.hoursAgo(hours);
  const days = Math.round(hours / 24);
  if (days === 1) return t.yesterday;
  if (days < 7) return t.daysAgo(days);
  return shortDate(iso, lang);
}
